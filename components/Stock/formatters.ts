'use client'

// Format number with FR locale
const fmt = (n: number) =>
  new Intl.NumberFormat("fr-FR", { minimumFractionDigits: 0 }).format(n);

// Format currency in XOF (West African Francs) - display as "Ar"
const fmtXOF = (n: number) => {
  const formatted = new Intl.NumberFormat("fr-FR", {
    style: "currency",
    currency: "XOF",
    minimumFractionDigits: 0
  }).format(n);
  // Replace "F CFA" with "Ar" for display
  return formatted.replace(/\s*F\s*CFA/, ' Ar');
};

// Format date as DD MMM YYYY
const fmtDate = (iso: string) => {
  const d = new Date(iso);
  return d.toLocaleDateString("fr-FR", {
    day: "2-digit",
    month: "short",
    year: "numeric"
  });
};

// Format date and time
const fmtDateTime = (iso: string) => {
  const d = new Date(iso);
  return d.toLocaleDateString("fr-FR", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit"
  });
};

// Calculate stock percentage
const stockPct = (lot: { quantiteActuelle: number; quantiteInitiale: number }) =>
  lot.quantiteInitiale > 0 ? (lot.quantiteActuelle / lot.quantiteInitiale) * 100 : 0;

// Calculate revenue generated by a lot
const argent = (lot: { quantiteVendue: number; prixInitial: number; marge: number }) =>
  lot.quantiteVendue * (lot.prixInitial + lot.marge);

export { fmt, fmtXOF, fmtDate, fmtDateTime, stockPct, argent };